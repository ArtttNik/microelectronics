USE work.dp32_types.ALL, work.alu_32_types.ALL;
LIBRARY ieee;
USE ieee.std_logic_1164.ALL;
ENTITY memory IS
    GENERIC (Tpd : TIME := unit_delay);
    PORT (
        d_bus : INOUT bus_bit_32 BUS;
        a_bus : IN bit_32;
        read  : IN STD_LOGIC;
        write : IN STD_LOGIC;
        ready : OUT STD_LOGIC);
END memory;
ARCHITECTURE behaviour OF memory IS
BEGIN
    PROCESS
        CONSTANT low_address  : INTEGER := 0;
        CONSTANT high_address : INTEGER := 65535;
        TYPE memory_array IS
            ARRAY(INTEGER RANGE low_address TO high_address) OF bit_32;
        VARIABLE address : INTEGER := 0;
        VARIABLE mem : memory_array :=
        (
        -- ============================================================
        -- INSERTION SORT ??? DP32
        -- ??????? ??????: [3, 6, 7, 5, 3, 5, 6, 2]
        -- ????????? ?????????: [2, 3, 3, 5, 5, 6, 6, 7]
        --
        -- ????????:
        --   r0  = 0 (??????????? ????)
        --   r1-r8 = ????????? (????????????? + ?????????)
        --   r9  = i (?????? ???????? ?????)
        --   r10 = j (?????? ??????????? ?????)
        --   r11 = key (??????? ???????)
        --   r12 = ?????????
        --   r13 = M[j] ?????????
        --   r14 = ????????? ????????? M[j]-key
        --
        -- ??????????? ????????? op_brq (50 cond 00 i8):
        --   cond bits[3:0] = cm_i cm_V cm_N cm_Z
        --   ???????: (cm_V&cc_V)|(cm_N&cc_N)|(cm_Z&cc_Z) = cm_i
        --   0x00 = ?????? (???????????)
        --   0x0A = ???? N=1  (????????? < 0)
        --   0x0B = ???? N=1 ??? Z=1  (????????? <= 0)
        --   i8 = target_addr - (branch_addr + 1)
        -- ============================================================

        -- [0]  r0 = r0 AND NOT r0 = 0
        X"07_00_00_00",  -- op_lmask r0,r0,r0

        -- [1..8]  ???????? ???????? ??????? ? ???????? r1..r8
        X"10_01_00_03",  -- r1 = r0 + 3  => r1 = 3
        X"10_02_00_06",  -- r2 = r0 + 6  => r2 = 6
        X"10_03_00_07",  -- r3 = r0 + 7  => r3 = 7
        X"10_04_00_05",  -- r4 = r0 + 5  => r4 = 5
        X"10_05_00_03",  -- r5 = r0 + 3  => r5 = 3
        X"10_06_00_05",  -- r6 = r0 + 5  => r6 = 5
        X"10_07_00_06",  -- r7 = r0 + 6  => r7 = 6
        X"10_08_00_02",  -- r8 = r0 + 2  => r8 = 2

        -- [9..16]  ?????????? ??????? ? ?????? M[0..7]
        X"31_01_00_00",  -- M[r0+0] = r1  => M[0] = 3
        X"31_02_00_01",  -- M[r0+1] = r2  => M[1] = 6
        X"31_03_00_02",  -- M[r0+2] = r3  => M[2] = 7
        X"31_04_00_03",  -- M[r0+3] = r4  => M[3] = 5
        X"31_05_00_04",  -- M[r0+4] = r5  => M[4] = 3
        X"31_06_00_05",  -- M[r0+5] = r6  => M[5] = 5
        X"31_07_00_06",  -- M[r0+6] = r7  => M[6] = 6
        X"31_08_00_07",  -- M[r0+7] = r8  => M[7] = 2

        -- [17]  i = 1
        X"10_09_00_01",  -- r9 = r0 + 1

        -- ============================================================
        -- LOOP_I [18]: for i = 1 to 7
        -- ============================================================

        -- [18]  key = M[i]
        X"30_0B_09_00",  -- r11 = M[r9+0]

        -- [19]  j = i - 1
        X"11_0A_09_01",  -- r10 = r9 - 1

        -- [20]  ?????????? ????? ?? ???????? j
        X"11_0C_0A_00",  -- r12 = r10 - 0  (N=1 ???? j<0)

        -- ============================================================
        -- WHILE [21]: while j >= 0 and M[j] > key
        -- ============================================================

        -- [21]  ???? j < 0 (N=1) ? END_WHILE [30]; i8 = 30-(21+1) = +8
        X"50_0A_00_08",  -- brq [N=1] -> END_WHILE

        -- [22]  r13 = M[j]
        X"30_0D_0A_00",  -- r13 = M[r10+0]

        -- [23]  r14 = M[j] - key  (????????????? N, Z)
        X"01_0E_0D_0B",  -- r14 = r13 - r11

        -- [24]  ???? M[j] <= key (N=1 ??? Z=1) ? END_WHILE [30]; i8 = 30-(24+1) = +5
        X"50_0B_00_05",  -- brq [N=1|Z=1] -> END_WHILE

        -- [25]  r12 = j + 1
        X"10_0C_0A_01",  -- r12 = r10 + 1

        -- [26]  M[j+1] = M[j]
        X"31_0D_0C_00",  -- M[r12+0] = r13

        -- [27]  j--
        X"11_0A_0A_01",  -- r10 = r10 - 1

        -- [28]  ???????? ????? ?? ?????? j
        X"11_0C_0A_00",  -- r12 = r10 - 0

        -- [29]  ??????????? ? WHILE [21]; i8 = 21-(29+1) = -9 = 0xF7
        X"50_00_00_F7",  -- brq [always] -> WHILE

        -- ============================================================
        -- END_WHILE [30]: M[j+1] = key
        -- ============================================================

        -- [30]  r12 = j + 1
        X"10_0C_0A_01",  -- r12 = r10 + 1

        -- [31]  M[j+1] = key
        X"31_0B_0C_00",  -- M[r12+0] = r11

        -- [32]  i++
        X"10_09_09_01",  -- r9 = r9 + 1

        -- [33]  r12 = i - 8
        X"11_0C_09_08",  -- r12 = r9 - 8

        -- [34]  ???? i < 8 (N=1) ? LOOP_I [18]; i8 = 18-(34+1) = -17 = 0xEF
        X"50_0A_00_EF",  -- brq [N=1] -> LOOP_I

        -- ============================================================
        -- DONE [35]: ?????? ??????????????? ?????? ? ????????
        -- ============================================================

        X"30_01_00_00",  -- r1 = M[0]
        X"30_02_00_01",  -- r2 = M[1]
        X"30_03_00_02",  -- r3 = M[2]
        X"30_04_00_03",  -- r4 = M[3]
        X"30_05_00_04",  -- r5 = M[4]
        X"30_06_00_05",  -- r6 = M[5]
        X"30_07_00_06",  -- r7 = M[6]
        X"30_08_00_07",  -- r8 = M[7]

        -- [43]  HALT: ??????????? ???? ?? ?????; i8 = -1 = 0xFF
        X"50_00_00_FF",  -- brq [always] -> self

        OTHERS => X"00_00_00_00");

    BEGIN
        d_bus <= NULL AFTER Tpd;
        ready <= '0' AFTER Tpd;
        WAIT UNTIL (read = '1') OR (write = '1');
        address := bits_to_int(a_bus);
        IF address >= low_address AND address <= high_address THEN
            IF write = '1' THEN
                ready <= '1' AFTER Tpd;
                WAIT UNTIL write = '0';
                mem(address) := d_bus;
            ELSE
                d_bus <= mem(address) AFTER Tpd;
                ready <= '1' AFTER Tpd;
                WAIT UNTIL read = '0';
            END IF;
        END IF;
    END PROCESS;
END behaviour;
