library ieee;
use ieee.std_logic_1164.all;

entity seventh is
  port
  (
    DIN : in std_logic_vector(3 downto 0);
    XORER : in std_logic_vector (7 downto 0);
    DOUT : out std_logic_vector(3 downto 0);
    ONE_ERR : out std_logic;
    DBL_ERR : out std_logic;
    CODED : out std_logic_vector(7 downto 0);
    AFTER_XOR : out std_logic_vector(7 downto 0)
  );
end seventh;

architecture structural of seventh is
  -- ?????????? ???????
  signal coderOut : std_logic_vector(7 downto 0);
  signal decoderInput : std_logic_vector(7 downto 0);
  
  -- ?????????? ?????????? ??????
  component CODER
    port
    (
      D : in std_logic_vector (3 downto 0);
      output : out std_logic_vector (7 downto 0)
    );
  end component;
  
  -- ?????????? ?????????? ????????
  component DECODER
    port
    (
      input : in std_logic_vector (7 downto 0);
      D : out std_logic_vector (3 downto 0);
      ONE_ERR : out std_logic;
      DBL_ERR : out std_logic
    );
  end component;
  
  -- ????????? ??? XOR ???????? (????? ??????????? ??? ????????? ?????????)
  component XOR_ARRAY
    port
    (
      A : in std_logic_vector(7 downto 0);
      B : in std_logic_vector(7 downto 0);
      Y : out std_logic_vector(7 downto 0)
    );
  end component;

begin
  -- ????????? ??????
  CODER_INST : CODER
    port map(
      D => DIN,
      output => coderOut
    );
    
  -- ????????? XOR ???????
  XOR_ARRAY_INST : XOR_ARRAY
    port map(
      A => coderOut,
      B => XORER,
      Y => decoderInput
    );
    
  -- ????????? ????????
  DECODER_INST : DECODER
    port map(
      input => decoderInput,
      D => DOUT,
      ONE_ERR => ONE_ERR,
      DBL_ERR => DBL_ERR
    );
    
  -- ?????????? ???????? ?????? ???????? ?????????? ????????
  CODED <= coderOut;
  AFTER_XOR <= decoderInput;
  
end structural;
